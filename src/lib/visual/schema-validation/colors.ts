const HEX_COLOR = /^#(?:[\da-f]{3}|[\da-f]{4}|[\da-f]{6}|[\da-f]{8})$/i;
const COLOR_FUNCTION = /^(rgb|rgba|hsl|hsla)\(\s*([\d\s.,%/+.-]+)\s*\)$/i;
const DESIGN_TOKEN =
  /^(?:brand|theme|palette|color|colors|visual|text|background|border|accent|semantic|surface)\.[a-z0-9][a-z0-9._-]*$/i;

export function isSafeVisualColor(value: string): boolean {
  const color = value.trim();
  if (color.length === 0) return false;
  if (HEX_COLOR.test(color)) return true;
  if (COLOR_FUNCTION.test(color)) return true;
  if (NAMED_COLORS.has(color.toLowerCase())) return true;
  return DESIGN_TOKEN.test(color);
}
