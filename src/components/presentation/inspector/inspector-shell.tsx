export interface InspectorShellProps {
  // Slide context
  activeSlide: SlideNode | undefined;
  deckChrome: DeckChromeConfig | undefined;
  selectedNode: SlideChildNode | undefined;
  selectedResolvedStyle?: StyleObject;
  selectedIds: string[];
  isDecorationSelected: boolean;
  selectedGeneratedSource?: "themeDecoration" | "deckChrome";
  diagnostics: PresentationDiagnostic[];
  layerDecorations?: readonly ResolvedRenderNode[];
  layerChrome?: readonly ResolvedRenderNode[];

  // Slide-level handlers
  onUpdateControls: (patch: Partial<SlideControls>) => void;
  onUpdateProps: (patch: Partial<SlideProps>) => void;
  onUpdateDeckChrome: (patch: Partial<DeckChromeConfig>) => void;
  onUpdateSlideAttributes: (patch: { name?: string; notes?: string }) => void;
  onUpdateSlideLocalStyle: (patch: StylePatch) => void;
  onResetSlideLocalStyle: () => void;
  onUpdateSlideSource: (source: NodeSourceMetadata | undefined) => void;
  onUploadSlideBackgroundImage?: () => void;

  // Node-level handlers
  onUpdateSelectedLayout: (patch: Record<string, unknown>) => void;
  onUpdateSelectedAttributes: (patch: {
    locked?: boolean;
    hidden?: boolean;
  }) => void;
  onUpdateSelectedContent: (patch: Record<string, unknown>) => void;
  onUpdateSelectedLocalStyle: (patch: StylePatch) => void;
  assetResolver?: (assetId: string) => string | undefined;
  onReplaceImage?: () => void;
  onReplaceVisual?: () => void;
  onResetToTheme: () => void;
  onUpdateSelectedSource: (source: NodeSourceMetadata | undefined) => void;
  onRefreshSelectedSource?: () => void;
  sourceRefreshPending?: boolean;
  onUnlinkSelectedSource?: () => void;
  onRelinkSelectedSource?: (block: SourceBlockIndexEntry) => void;
  selectedSourceClassification?: SourceLinkClassification;
  sourceBlocks?: readonly SourceBlockIndexEntry[];
  onChangeStyleBinding: (binding: StyleBinding) => void;
  onAlignSelection: (mode: SelectionAlignMode) => void;
  onDistributeSelection: (mode: SelectionDistributeMode) => void;
  onMatchSize: (mode: SelectionMatchSizeMode) => void;
  onReorderSelection?: (mode: CurrentObjectReorderMode) => void;
  onGroupSelection: () => void;
  onUngroupSelection: () => void;

  // Layers
  onSelectLayer: (nodeId: string) => void;
  onUpdateLayer: (
    nodeId: string,
    patch: { name?: string; locked?: boolean; hidden?: boolean },
  ) => void;
  onReorderLayer: (nodeId: string, targetIndex: number) => void;

  // Decoration
  onDetachDecoration: () => void;

  // Diagnostics
  onDiagnosticAction: (
    action: DiagnosticAction,
    diagnostic: PresentationDiagnostic,
  ) => void;

  // Template
  TEMPLATE_OPTIONS: { kind: SemanticTemplateKind; label: string }[];
  activeTemplate: { layouts: { id: string }[] } | undefined;
  activeLayoutId: string | undefined;
  onReapplyTemplate: (kind: SemanticTemplateKind, layoutId?: string) => void;

  // Mode
  selectionMode: "normal" | "layers";
  onToggleSelectionMode: () => void;
  initialPanel?: InspectorPanelId;
  onClose?: () => void;
}

export function InspectorShell({
  activeSlide,
  deckChrome,
  selectedNode,
  selectedResolvedStyle,
  selectedIds,
  isDecorationSelected,
  selectedGeneratedSource,
  diagnostics,
  layerDecorations,
  layerChrome,
  onUpdateControls,
  onUpdateProps,
  onUpdateDeckChrome,
  onUpdateSlideAttributes,
  onUpdateSlideLocalStyle,
  onResetSlideLocalStyle,
  onUpdateSlideSource,
  onUploadSlideBackgroundImage,
  onUpdateSelectedLayout,
  onUpdateSelectedAttributes,
  onUpdateSelectedContent,
  onUpdateSelectedLocalStyle,
  assetResolver,
  onReplaceImage,
  onReplaceVisual,
  onResetToTheme,
  onUpdateSelectedSource,
  onRefreshSelectedSource,
  sourceRefreshPending = false,
  onUnlinkSelectedSource,
  onRelinkSelectedSource,
  selectedSourceClassification,
  sourceBlocks,
  onChangeStyleBinding,
  onAlignSelection,
  onDistributeSelection,
  onMatchSize,
  onReorderSelection = () => undefined,
  onGroupSelection,
  onUngroupSelection,
  onSelectLayer,
  onUpdateLayer,
  onReorderLayer,
  onDetachDecoration,
  onDiagnosticAction,
  TEMPLATE_OPTIONS,
  activeTemplate,
  activeLayoutId,
  onReapplyTemplate,
  selectionMode,
  onToggleSelectionMode,
  initialPanel,
  onClose,
}: InspectorShellProps): JSX.Element {
  const nodeForRouting = isDecorationSelected ? null : (selectedNode ?? null);
  const multiSelect = selectedIds.length > 1;
  const panels = availablePanels(nodeForRouting, {
    multiSelect,
    isDecoration: isDecorationSelected,
    hasDiagnostics: diagnostics.length > 0,
  });
  const defaultPanel = defaultPanelForNode(
    nodeForRouting,
    isDecorationSelected,
  );

  const [activePanel, setActivePanel] = useState<InspectorPanelId>(() =>
    resolveInspectorPanelContinuity({
      activePanel: initialPanel,
      panels,
      defaultPanel,
    }),
  );

  const effectivePanel = resolveInspectorPanelContinuity({
    activePanel,
    panels,
    defaultPanel,
  });

  const inspectorPanelSelectId = useId();
  const inspectorPanelId = (panelId: string) =>
    `presentation-inspector-panel-${panelId}`;

  function handlePanelSelect(panel: InspectorPanelId) {
    setActivePanel(panel);
    const nextLayersMode = panel === "layers";
    if (nextLayersMode !== (selectionMode === "layers")) {
      onToggleSelectionMode();
    }
  }

  // Identity label next to the panel selector
  let identityLabel = "Inspector";
  if (isDecorationSelected) {
    identityLabel =
      selectedGeneratedSource === "deckChrome" ? "Deck chrome" : "Decoration";
  } else if (selectedNode) {
    identityLabel =
      selectedNode.type.charAt(0).toUpperCase() + selectedNode.type.slice(1);
    if (selectedNode.name) identityLabel = selectedNode.name;
  } else if (activeSlide) {
    identityLabel = activeSlide.name ?? "Slide";
  }

  return (
    <aside
      role="region"
      aria-label="Inspector"
      className="relative z-panel flex h-full w-80 shrink-0 flex-col overflow-hidden bg-ds-surface"
    >
      {/* Identity header */}
      <div className="flex items-center justify-between gap-2 border-b border-ds-border-subtle px-3 py-2">
        <span className="truncate text-xs font-medium text-ds-text-primary">
          {identityLabel}
        </span>
        <div className="flex shrink-0 items-center gap-1.5">
          <InspectorPanelSelect
            id={inspectorPanelSelectId}
            panels={panels}
            value={effectivePanel}
            diagnosticsCount={diagnostics.length}
            onChange={handlePanelSelect}
          />
          {onClose ? (
            <button
              type="button"
              aria-label="Close inspector"
              onClick={onClose}
              className="flex h-7 w-7 items-center justify-center rounded-ds-sm text-ds-text-muted transition-colors hover:bg-ds-state-hover hover:text-ds-text-primary"
            >
              <X size={14} aria-hidden="true" />
            </button>
          ) : null}
        </div>
      </div>

      {/* Panel content */}
      <div
        id={inspectorPanelId(effectivePanel)}
        role="tabpanel"
        aria-labelledby={inspectorPanelSelectId}
        className="min-h-0 flex-1 overflow-y-auto"
      >
        {/* Slide panel */}
        {effectivePanel === "slide" && activeSlide && (
          <PanelSection>
            <section className="flex flex-col gap-1.5 px-3 py-2.5">
              <h4 className="text-[10px] font-bold uppercase tracking-[0.06em] text-ds-text-muted">
                Template
              </h4>
              <label className="flex flex-col gap-1 text-xs text-ds-text-secondary">
                Kind
                <select
                  value={activeSlide.template.kind}
                  onChange={(e) =>
                    onReapplyTemplate(
                      e.currentTarget.value as SemanticTemplateKind,
                    )
                  }
                  className="rounded-[var(--ds-radius-md,8px)] border border-ds-border-subtle bg-ds-surface px-2 py-1 text-xs text-ds-text-primary"
                >
                  {TEMPLATE_OPTIONS.map((t) => (
                    <option key={t.kind} value={t.kind}>
                      {t.label}
                    </option>
                  ))}
                </select>
              </label>
              {activeTemplate && (
                <label className="flex flex-col gap-1 text-xs text-ds-text-secondary">
                  Layout
                  <select
                    value={activeLayoutId ?? activeTemplate.layouts[0]?.id}
                    onChange={(e) =>
                      onReapplyTemplate(
                        activeSlide.template.kind,
                        e.currentTarget.value,
                      )
                    }
                    className="rounded-[var(--ds-radius-md,8px)] border border-ds-border-subtle bg-ds-surface px-2 py-1 text-xs text-ds-text-primary"
                  >
                    {activeTemplate.layouts.map((l) => (
                      <option key={l.id} value={l.id}>
                        {l.id}
                      </option>
                    ))}
                  </select>
                </label>
              )}
            </section>
            <SlideControlsPanel
              controls={activeSlide.controls}
              props={activeSlide.props}
              onUpdateControls={onUpdateControls}
              onUpdateProps={onUpdateProps}
            />
            <DeckChromePanel
              chrome={deckChrome}
              slideProps={activeSlide.props}
              onUpdateChrome={onUpdateDeckChrome}
              onUpdateSlideProps={onUpdateProps}
            />
            <SlideSettingsPanel
              slide={activeSlide}
              onUpdateSlide={onUpdateSlideAttributes}
              onUpdateSource={onUpdateSlideSource}
              onUpdateLocalStyle={onUpdateSlideLocalStyle}
              onResetLocalStyle={onResetSlideLocalStyle}
              assetResolver={assetResolver}
              onUploadBackgroundImage={onUploadSlideBackgroundImage}
            />
          </PanelSection>
        )}

        {/* Notes panel */}
        {effectivePanel === "notes" && (
          <NotesPanel
            notes={activeSlide?.notes}
            onUpdateNotes={(notes) => onUpdateSlideAttributes({ notes })}
          />
        )}

        {/* Text panel — content + style controls */}
        {(effectivePanel === "text" || effectivePanel === "shape") &&
          selectedNode &&
          !isDecorationSelected && (
            <PanelSection>
              <div className="px-3 py-2">
                <LocalOverrideBadge
                  localStyle={selectedNode.localStyle}
                  onResetToTheme={onResetToTheme}
                />
              </div>
              <NodeContentPanel
                node={selectedNode}
                onUpdateContent={onUpdateSelectedContent}
              />
              <LocalStylePanel
                node={selectedNode}
                resolvedStyle={selectedResolvedStyle}
                onUpdateLocalStyle={onUpdateSelectedLocalStyle}
              />
            </PanelSection>
          )}

        {/* Image / visual / line / table content panel */}
        {(effectivePanel === "image" ||
          effectivePanel === "visual" ||
          effectivePanel === "line" ||
          effectivePanel === "table") &&
          selectedNode &&
          !isDecorationSelected && (
            <PanelSection>
              <div className="px-3 py-2">
                <LocalOverrideBadge
                  localStyle={selectedNode.localStyle}
                  onResetToTheme={onResetToTheme}
                />
              </div>
              <NodeContentPanel
                node={selectedNode}
                onUpdateContent={onUpdateSelectedContent}
                assetResolver={assetResolver}
                onReplaceImage={
                  selectedNode.type === "image" ? onReplaceImage : undefined
                }
                onReplaceVisual={
                  selectedNode.type === "visual" ? onReplaceVisual : undefined
                }
              />
              <LocalStylePanel
                node={selectedNode}
                resolvedStyle={selectedResolvedStyle}
                onUpdateLocalStyle={onUpdateSelectedLocalStyle}
              />
            </PanelSection>
          )}

        {/* Adjust panel */}
        {effectivePanel === "adjust" && selectedNode && (
          <AdjustPanel
            node={selectedNode}
            onUpdateContent={onUpdateSelectedContent}
            onUpdateLocalStyle={onUpdateSelectedLocalStyle}
          />
        )}

        {/* Arrange panel */}
        {effectivePanel === "arrange" && multiSelect && (
          <MultiArrangePanel
            selectedCount={selectedIds.length}
            onAlignSelection={onAlignSelection}
            onDistributeSelection={onDistributeSelection}
            onMatchSize={onMatchSize}
            onReorderSelection={onReorderSelection}
            onGroupSelection={onGroupSelection}
            onUngroupSelection={onUngroupSelection}
          />
        )}

        {effectivePanel === "arrange" &&
          !multiSelect &&
          selectedNode &&
          !isDecorationSelected && (
            <PanelSection>
              <div className="px-3 py-2">
                <LocalOverrideBadge
                  localStyle={selectedNode.localStyle}
                  onResetToTheme={onResetToTheme}
                />
              </div>
              <SingleArrangePanel
                onAlignSelection={onAlignSelection}
                onReorderSelection={onReorderSelection}
              />
              <NodeGeometryPanel
                node={selectedNode}
                onUpdateLayout={
                  onUpdateSelectedLayout as Parameters<
                    typeof NodeGeometryPanel
                  >[0]["onUpdateLayout"]
                }
                onUpdateAttributes={onUpdateSelectedAttributes}
              />
            </PanelSection>
          )}

        {/* Effects panel */}
        {effectivePanel === "effects" && (
          <EffectsPanel
            node={selectedNode}
            onUpdateLocalStyle={onUpdateSelectedLocalStyle}
            onResetToTheme={onResetToTheme}
          />
        )}

        {/* Source panel */}
        {effectivePanel === "source" &&
          selectedNode &&
          !isDecorationSelected && (
            <PanelSection>
              <NodeSourcePanel
                node={selectedNode}
                onUpdateSource={onUpdateSelectedSource}
                onRefreshSource={onRefreshSelectedSource}
                sourceRefreshPending={sourceRefreshPending}
                onUnlinkSource={onUnlinkSelectedSource}
                onRelinkSource={onRelinkSelectedSource}
                classification={selectedSourceClassification}
                availableBlocks={sourceBlocks}
              />
            </PanelSection>
          )}

        {/* Style panel */}
        {effectivePanel === "style" &&
          selectedNode &&
          !isDecorationSelected && (
            <PanelSection>
              <StyleBindingPanel
                role={selectedNode.role}
                binding={selectedNode.style}
                onChangeStyleBinding={onChangeStyleBinding}
              />
              <LocalStylePanel
                node={selectedNode}
                resolvedStyle={selectedResolvedStyle}
                onUpdateLocalStyle={onUpdateSelectedLocalStyle}
              />
            </PanelSection>
          )}

        {/* Layers panel */}
        {effectivePanel === "layers" && activeSlide && (
          <PanelSection>
            <LayersPanel
              nodes={activeSlide.children}
              decorations={layerDecorations}
              chrome={layerChrome}
              selectedIds={selectedIds}
              onSelectNode={onSelectLayer}
              onUpdateNode={onUpdateLayer}
              onReorderNode={onReorderLayer}
            />
          </PanelSection>
        )}

        {/* Decoration panel */}
        {effectivePanel === "decoration" && isDecorationSelected && (
          <DecorationPanel
            source={selectedGeneratedSource ?? "themeDecoration"}
            onDetach={onDetachDecoration}
          />
        )}

        {/* Diagnostics panel */}
        {effectivePanel === "diagnostics" && (
          <PanelSection>
            <DiagnosticsPanel
              diagnostics={diagnostics}
              onAction={onDiagnosticAction}
              hideInfo={false}
            />
          </PanelSection>
        )}
      </div>
    </aside>
  );
}
