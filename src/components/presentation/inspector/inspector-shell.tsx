function AdjustPanel({
  node,
  onUpdateContent,
  onUpdateLocalStyle,
}: {
  node: SlideChildNode;
  onUpdateContent: (patch: Record<string, unknown>) => void;
  onUpdateLocalStyle: (patch: StylePatch) => void;
}) {
  if (node.type !== "image") {
    return (
      <PanelSection>
        <div className="p-3 text-xs text-ds-text-muted">
          Image adjustment controls are available for image nodes.
        </div>
      </PanelSection>
    );
  }

  const crop = node.content.crop ?? { top: 0, right: 0, bottom: 0, left: 0 };
  const opacity = node.localStyle?.opacity ?? 1;
  const brightness = node.localStyle?.image?.brightness ?? 1;
  const contrast = node.localStyle?.image?.contrast ?? 1;
  const saturation = node.localStyle?.image?.saturation ?? 1;
  const blur =
    node.localStyle?.effect?.kind === "blur"
      ? (node.localStyle.effect.radiusPt ?? 0)
      : 0;

  return (
    <PanelSection>
      <section className="flex flex-col gap-3 px-3 py-2.5">
        <h4 className="text-[10px] font-bold uppercase tracking-[0.06em] text-ds-text-muted">
          Image Adjust
        </h4>
        <label className="flex flex-col gap-1 text-xs text-ds-text-secondary">
          Fit mode
          <select
            value={node.content.fit ?? "cover"}
            onChange={(event) =>
              onUpdateContent({ fit: event.currentTarget.value })
            }
            className="rounded-[var(--ds-radius-md,8px)] border border-ds-border-subtle bg-ds-surface px-2 py-1 text-xs text-ds-text-primary"
          >
            {(["contain", "cover", "fill", "none"] as const).map((fit) => (
              <option key={fit} value={fit}>
                {fit}
              </option>
            ))}
          </select>
        </label>
        <RangeField
          label="Opacity"
          value={opacity}
          min={0}
          max={1}
          step={0.05}
          display={(value) => `${Math.round(value * 100)}%`}
          onChange={(value) => onUpdateLocalStyle({ opacity: value })}
        />
        <RangeField
          label="Brightness"
          value={brightness}
          min={0}
          max={2}
          step={0.05}
          display={(value) => `${Math.round(value * 100)}%`}
          onChange={(value) =>
            onUpdateLocalStyle({ image: { brightness: value } })
          }
        />
        <RangeField
          label="Contrast"
          value={contrast}
          min={0}
          max={2}
          step={0.05}
          display={(value) => `${Math.round(value * 100)}%`}
          onChange={(value) =>
            onUpdateLocalStyle({ image: { contrast: value } })
          }
        />
        <RangeField
          label="Saturation"
          value={saturation}
          min={0}
          max={2}
          step={0.05}
          display={(value) => `${Math.round(value * 100)}%`}
          onChange={(value) =>
            onUpdateLocalStyle({ image: { saturation: value } })
          }
        />
        <RangeField
          label="Blur"
          value={blur}
          min={0}
          max={32}
          step={1}
          display={(value) => `${value} pt`}
          onChange={(value) =>
            onUpdateLocalStyle({
              effect:
                value === 0
                  ? { kind: "none" }
                  : { kind: "blur", radiusPt: value },
            })
          }
        />
        <div className="grid grid-cols-2 gap-2">
          {(["top", "right", "bottom", "left"] as const).map((side) => (
            <NumberField
              key={side}
              label={`Crop ${side}`}
              value={crop[side]}
              min={0}
              max={95}
              onChange={(value) => {
                const nextCrop = updateImageCropSide(crop, side, value);
                if (nextCrop !== undefined) {
                  onUpdateContent({ crop: nextCrop });
                }
              }}
            />
          ))}
        </div>
        <button
          type="button"
          onClick={() =>
            onUpdateContent({
              crop: { top: 0, right: 0, bottom: 0, left: 0 },
            })
          }
          className="self-start rounded-[var(--ds-radius-sm,6px)] border border-ds-border-subtle px-2 py-1 text-xs font-medium text-ds-text-secondary hover:bg-ds-state-hover"
        >
          Reset crop
        </button>
        <button
          type="button"
          onClick={() =>
            onUpdateLocalStyle({
              opacity: 1,
              image: { brightness: 1, contrast: 1, saturation: 1 },
              effect: { kind: "none" },
            })
          }
          className="self-start rounded-[var(--ds-radius-sm,6px)] border border-ds-border-subtle px-2 py-1 text-xs font-medium text-ds-text-secondary hover:bg-ds-state-hover"
        >
          Reset adjustments
        </button>
      </section>
    </PanelSection>
  );
}

type LocalStyleUpdater = (patch: StylePatch) => void;
type LocalEffectStyle = NonNullable<StylePatch["effect"]>;
type LocalShadowStyle = StylePatch["shadow"];

function resolveEffectForKind(kind: string): EffectStyle {
  if (kind === "blur") {
    return { kind: "blur", radiusPt: 12 };
  }

  if (kind === "glow") {
    return {
      kind: "glow",
      color: DEFAULT_GLOW_COLOR,
      blurPt: 14,
      opacity: 0.35,
    };
  }

  if (kind === "glass") {
    return { kind: "glass", intensity: "medium" };
  }

  return { kind: "none" };
}

function shadowPatch(
  shadow: LocalShadowStyle,
  patch: Partial<ShadowStyle>,
): ShadowStyle {
  return {
    xPt: patch.xPt ?? shadow?.xPt ?? DEFAULT_SHADOW.xPt,
    yPt: patch.yPt ?? shadow?.yPt ?? DEFAULT_SHADOW.yPt,
    blurPt: patch.blurPt ?? shadow?.blurPt ?? DEFAULT_SHADOW.blurPt,
    color:
      patch.color ??
      (typeof shadow?.color === "string" ? shadow.color : DEFAULT_SHADOW.color),
    opacity: patch.opacity ?? shadow?.opacity ?? DEFAULT_SHADOW_OPACITY,
  };
}

